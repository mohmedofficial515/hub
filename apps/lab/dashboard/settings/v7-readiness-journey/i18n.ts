type ArForms = { zero?: string; one: string; two: string; few: string; many: string; other: string };

const arRules = new Intl.PluralRules('ar');
/** Arabic count phrase: `{n}` in a form is replaced by the number. */
function arCount(n: number, forms: ArForms): string {
  const cat = arRules.select(n) as keyof ArForms;
  const form = (n === 0 && forms.zero) || forms[cat] || forms.other;
  return form.replace('{n}', String(n));
}
const enCount = (n: number, one: string, other: string) => (n === 1 ? one : other).replace('{n}', String(n));

