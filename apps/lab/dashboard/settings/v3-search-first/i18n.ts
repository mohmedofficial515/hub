const arNf = new Intl.NumberFormat('ar-u-nu-latn');
const enNf = new Intl.NumberFormat('en');
const arRules = new Intl.PluralRules('ar');

/** Arabic count phrase: forms = [one (full phrase), two (full phrase), few 3–10, many 11–99, other]. */
function arCount(n: number, f: Forms, nf?: string): string {
  const num = nf ?? arNf.format(n);
  switch (arRules.select(n)) {
    case 'one':
      return f[0];
    case 'two':
      return f[1];
    case 'few':
      return `${num} ${f[2]}`;
    case 'many':
      return `${num} ${f[3]}`;
    default:
      return `${num} ${f[4]}`;
  }
}
